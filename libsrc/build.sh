#!/bin/sh
# libsrc/build.sh -- the library modules that are written in the human notation (libsrc/*.hum.imo, class-checked as programs) are translated into the spec
# notation of the prelude (lib/*.imo).  Needs build/rustimo; a module that is already part of the prelude is left out of it while it is translated.
#   libsrc/build.sh [NAME ...]        translate the named modules (default: all)
cd "$(dirname "$0")/.." || exit 1
[ -x build/rustimo ] || { echo "libsrc/build.sh: build/rustimo is missing (make rustimo)" >&2; exit 1; }
if [ $# -eq 0 ]; then set -- $(ls libsrc/*.hum.imo | sed 's|libsrc/||; s|\.hum\.imo$||'); fi
for name in "$@"; do
  src=libsrc/$name.hum.imo
  out=lib/$name.imo
  {
    printf '⍝ lib/%s.imo — spec notation — trusted prelude — generated by libsrc/build.sh from libsrc/%s.hum.imo: edit that file, not this one\n' "$name" "$name"
    sed -n 's/^-- \{0,1\}/⍝ /p' "$src" | sed '/^[^⍝]/q'
    # a helper written _name in the human notation is name′ in the prelude (the prime is how the library marks its own helpers)
    I1_SKIP_LIB="$name.imo" build/rustimo translate "$src" --to spec | sed -E 's/(^|[ (])_([^ ()]+)/\1\2′/g' || exit 1
  } > "$out.tmp" && mv "$out.tmp" "$out" || { rm -f "$out.tmp"; exit 1; }
done
