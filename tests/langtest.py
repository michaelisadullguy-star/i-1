"""langtest.py -- test the library against Python oracles, through the command line of the core under test.

A test is  (label, hum expression, class, expected Python value).  The tests of one suite become ONE human-notation program

    main in List(Bool) := [ eq(expression, literal of the expected value), … ]

which is class-checked (so the signatures of the library are tested too), run by `run`, and must print only `true`.  Equality is
decided by the language (`==`, `iff`, `eqlist` …), the expected value is a literal written by this module from the Python value, so
nothing but the comparison depends on the code under test.

Classes are written as Python data:   'N' ℕ   'Z' ℤ   'Q' ℚ[i]/ℚ   'B' Bool   'S' String   'C' Char   ('L', c) List   ('P', c1, c2) Pair
and for the class of a definition the human spelling is built by hum_class().
"""
import os, re, subprocess, sys, tempfile, time
from fractions import Fraction
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import harness
from harness import CORE, cli

HUM = {'N': r'\NN', 'Z': r'\ZZ', 'Q': r'\QQ', 'G': r'\Z', 'Qi': r'\Q', 'B': 'Bool', 'S': 'String', 'C': 'Char'}


def hum_class(c):
    if isinstance(c, str): return HUM[c]
    if c[0] == 'L': return f'List({hum_class(c[1])})'
    if c[0] == 'P': return f'Pair({hum_class(c[1])}, {hum_class(c[2])})'
    raise ValueError(c)


def lit(v, c):
    """a Python value as a human-notation literal of class c"""
    if c in ('N', 'Z', 'Q', 'G', 'Qi'):
        f = Fraction(v)
        return str(f.numerator) if f.denominator == 1 else f'{f.numerator}/{f.denominator}'
    if c == 'B': return 'true' if v else 'false'
    if c == 'S': return '"' + v.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\t', '\\t') + '"'
    if c == 'C': return "'" + v.replace('\\', '\\\\').replace("'", "\\'") + "'"
    if c[0] == 'L': return '[' + ', '.join(lit(x, c[1]) for x in v) + ']'
    if c[0] == 'P': return f'pair({lit(v[0], c[1])}, {lit(v[1], c[2])})'
    raise ValueError(c)


_n = [0]
def eq(c, a, b):
    """a human-notation Boolean: a and b are equal at class c"""
    if c in ('N', 'Z', 'Q', 'G', 'Qi', 'S', 'C'): return f'(({a}) == ({b}))'
    if c == 'B': return f'(({a}) iff ({b}))'
    if c[0] == 'L':
        _n[0] += 1; u, w = f'eu{_n[0]}'.replace('1', 'a'), f'ev{_n[0]}'.replace('1', 'a')
        u = re.sub(r'\d', lambda m: 'abcdefghij'[int(m.group())], u); w = re.sub(r'\d', lambda m: 'abcdefghij'[int(m.group())], w)
        inner = eq(c[1], u, w)
        return f'eqlist(({u} in {hum_class(c[1])} |-> ({w} in {hum_class(c[1])} |-> {inner})), {a}, {b})'
    if c[0] == 'P':
        return f'({eq(c[1], f"fst({a})", f"fst({b})")} and {eq(c[2], f"snd({a})", f"snd({b})")})'
    raise ValueError(c)


class Suite:
    def __init__(self, title, prelude=''):
        self.title, self.tests, self.prelude = title, [], prelude
    def add(self, label, expr, cls, expected):
        self.tests.append((label, expr, cls, expected))
    def program(self, tests):
        lines = [self.prelude] if self.prelude else []
        els = [eq(c, e, lit(x, c)) for (_, e, c, x) in tests]
        lines.append('main in List(Bool) := [' + ',\n  '.join(els) + ']')
        return '\n'.join(lines) + '\n'
    def selfcheck(self, tests, source, index, total):
        """the same batch as a standalone program that checks itself: it prints  PASS n  or  FAIL label label …  (a file of tests/imo, run directly by any core)"""
        lines = [f'-- {self.title}: checks {index * 150 + 1} to {index * 150 + len(tests)} of {total}.  Generated by tests/langtest.py from {source}: the expected values were computed by independent Python oracles;',
                 '-- run it with  ./i1 --impl NAME run THIS_FILE  on any core: it prints  PASS n  when every check holds, and  FAIL  and the labels of the failed checks otherwise.']
        if self.prelude: lines.append(self.prelude)
        els = [eq(c, e, lit(x, c)) for (_, e, c, x) in tests]
        lines.append('checkvalues in List(Bool) := [' + ',\n  '.join(els) + ']')
        # a label is text only: the brackets of the source text are replaced (the reader of a statement counts brackets, also inside a string, and a label cut at 140 characters may leave one open)
        BR = {ord(c): d for c, d in zip('()[]{}', '⟨⟩⟦⟧⦃⦄')}
        labels = [lit(re.sub(r'\s+', ' ', t[0]).replace('--', '- -').translate(BR)[:140], 'S') for t in tests]
        lines.append('checklabels in List(String) := [' + ',\n  '.join(labels) + ']')
        lines.append('failedlabels in List(String) := filter((w in String |-> not isnil(w)), zipwith((ok in Bool |-> (name in String |-> if(ok, "", name))), checkvalues, checklabels))')
        lines.append(f'main in String := if(isnil(failedlabels), "PASS {len(tests)}", "FAIL " ++ unwords(failedlabels))')
        return '\n'.join(lines) + '\n'
    def emit(self, directory, source, batch=150):
        os.makedirs(directory, exist_ok=True)
        stem = re.sub(r'^test_|\.py$', '', os.path.basename(source))
        n = 0
        for i, lo in enumerate(range(0, len(self.tests), batch)):
            part = self.tests[lo:lo + batch]
            with open(os.path.join(directory, f'{stem}-{i + 1:02d}.hum.imo'), 'w', encoding='utf-8', newline='\n') as f: f.write(self.selfcheck(part, f'tests/{os.path.basename(source)}', i, len(self.tests)))
            n += 1
        return n
    def run(self, batch=150, timeout=900):
        """returns (passed, failed list of (label, detail))"""
        failed, passed = [], 0
        for lo in range(0, len(self.tests), batch):
            part = self.tests[lo:lo + batch]
            text = self.program(part); t_b = time.time()
            with tempfile.TemporaryDirectory() as d:
                path = os.path.join(d, 'langtest.hum.imo')
                with open(path, 'w', encoding='utf-8') as f: f.write(text)
                try:
                    p = subprocess.run(cli() + ['run', path], capture_output=True, text=True, encoding='utf-8', timeout=timeout)
                except subprocess.TimeoutExpired:
                    failed += [(l, 'timeout') for (l, _, _, _) in part]; continue
            if os.environ.get('LANGTEST_V'): print(f'  batch {lo}..{lo + len(part)}: rc={p.returncode} {time.time() - t_b:.1f}s', file=sys.stderr, flush=True)
            out = p.stdout.strip()
            if p.returncode != 0 or not out.startswith('['):
                msg = (p.stderr or p.stdout).strip().splitlines()
                detail = (msg[-1] if msg else f'rc={p.returncode}')[:300]
                if len(part) == 1:
                    failed.append((part[0][0], f'{part[0][1]} → {detail}')); continue
                for t in part:                       # a class error or a crash in one test must not hide the others: one by one
                    r = Suite(self.title, self.prelude); r.tests = [t]
                    pr, fl = r.run(batch=1, timeout=timeout)
                    passed += pr; failed += fl
                continue
            vals = [v.strip() for v in out.strip('[]').split(',')]
            for t, v in zip(part, vals):
                if v == 'true': passed += 1
                else: failed.append((t[0], f'{t[1]} → expected {t[3]!r}, the comparison said {v}'))
            if len(vals) != len(part): failed.append(('(count)', f'{len(vals)} results for {len(part)} tests'))
        return passed, failed


def report(suite):
    t0 = time.time()
    emit_dir = os.environ.get('LANGTEST_EMIT')
    if emit_dir:                                   # write the tests as standalone .imo programs instead of running them
        source = os.path.abspath(sys.modules['__main__'].__file__)
        k = suite.emit(emit_dir, source)
        print(f"EMIT  {suite.title}: {len(suite.tests)} checks in {k} files of {emit_dir}")
        return True
    passed, failed = suite.run()
    n = len(suite.tests)
    print(f"{'PASS' if not failed else 'FAIL'}  {suite.title}: {passed}/{n} tests ({time.time() - t0:.1f}s)")
    for label, detail in failed[:25]: print(f'    FAIL {label}: {detail}')
    print(f"\n{passed}/{n} passed  ({time.time() - t0:.1f}s)")          # the line tests/run_suites.py reads
    return not failed
