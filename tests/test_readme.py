"""test_readme.py -- the facts that are written BY HAND in the README sources (readme/part*.md) are checked against the implementation.
(Everything else in the README is generated by pymo/mkreadme.py from running the code.)     python3 tests/test_readme.py"""
import os, re, sys, time
from fractions import Fraction as Fr
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'pymo')); sys.path.insert(0, HERE)
import harness; harness.pymo_only('the checker messages and numbers quoted in the README')      # the error messages are cases of tests/conformance (err.*)
import imo
from imo import Program
from base_b import val, to_digits, numeral, gadd, gmul

RESULTS = []
def report(label, ok, extra=''):
    RESULTS.append(bool(ok)); print(f"{'PASS' if ok else 'FAIL'}  {label} {extra}"); sys.stdout.flush()
def part(n): return open(os.path.join(ROOT, 'readme', f'part{n}.md'), encoding='utf-8').read()
def norm(s): return re.sub(r'\s+', ' ', s).strip()

def verdict(text, notation='spec'):
    q = Program()
    for f in imo.PRELUDE: q.add_file(f, trusted=True)
    q.add_file(os.path.join(ROOT, 'examples', 'target.spec.imo'))
    q.add_text(text, 't', notation=notation)
    return q.check(collect=True)

def pi_N(N):
    s = t = Fr(2)
    for k in range(1, N + 1): t = t * k / (2 * k + 1); s += t
    return s
def e_N(N):
    s = t = Fr(1)
    for k in range(1, N + 1): t = t / k; s += t
    return s

def main():
    t0 = time.time()
    p1, p4, p5, p6 = part(1), part(4), part(5), part(6)
    import mkcarry

    # ---- §7.6: every row of the error-message table is what the checker really says
    sec = p5.split('### 7.6')[1].split('### 7.7')[0]
    rows = [ln for ln in sec.split('\n') if ln.startswith('| `')]
    ok, n = True, 0
    for ln in rows:
        cells = [c.strip() for c in re.split(r'(?<!\\)\|', ln)[1:-1]]
        prog = [x.strip('` ') for x in cells[0].split(' / ')]
        want = cells[1].strip('`')
        hum = any(' in \\' in x for x in prog)
        errs = verdict('\n'.join(prog), 'hum' if hum else 'spec')
        got = [f"{w}: {m}" if not m.startswith(str(w)) else m for _, w, m in errs]
        hit = any(norm(want) == norm(g) for g in got)
        ok &= hit; n += 1
        if not hit: print("   ?", prog, "\n     README says:", want, "\n     checker says:", got)
    report(f"§7.6: all {n} error messages in the README are exactly the checker's messages", ok and n >= 8)

    # ---- §7.4: classes of the arithmetic examples
    def lands_in(body, cls):
        return not verdict(f"k ∶ {cls}\nk ≔ {body}")
    def not_in(body, cls, found):
        e = verdict(f"k ∶ {cls}\nk ≔ {body}")
        return bool(e) and f"class {found}" in e[0][2]
    ok = lands_in("(⊞ 1 1100)", "ℕ") and lands_in("(⊞ (⊖ 1101) 1)", "ℤ") and not_in("(⊞ (⊖ 1101) 1)", "ℕ", "ℤ")
    prod = "(⊠ (⊞ 1 (⊠ 1100 11)) (⊟ 1101 11))"
    ok &= lands_in(prod, "ℤ[i]") and not_in(prod, "ℤ", "ℤ[i]")
    report("§7.4: `1 + 1100` is ℕ, `-3 + 1` is ℤ, `(1 + 2*i) * (3 - i)` is ℤ[i]", ok)
    ok = len([1 for (f, st, t) in prelude_statements() if st[0] == 'decl' and st[1] == '⊞']) == 5
    report("§7.4: the prelude declares ⊞ five times", ok)

    # ---- §6.1: powers of the base and the table of numerals
    pw, z, line = [], (1, 0), []
    for k in range(9):
        re_, im_ = z
        txt = (f"{re_}" if re_ else '') + (('' if not re_ else (' + ' if im_ > 0 else ' − ')) + ('' if abs(im_) == 1 else str(abs(im_))) + 'i' if im_ else '')
        if not re_ and im_: txt = ('−' if im_ < 0 else '') + ('' if abs(im_) == 1 else str(abs(im_))) + 'i'
        line.append(f"b{'⁰¹²³⁴⁵⁶⁷⁸'[k]} = {txt}".replace('-', '−'))
        z = gmul(z, (-1, 1))
    ok = all(x in p4 for x in line)
    if not ok: print("   ?", [x for x in line if x not in p4])
    report("§6.1: the nine powers b⁰ … b⁸ printed in the README are right", ok)
    table = {(0, 0): '0', (1, 0): '1', (0, 1): '11', (2, 0): '1100', (3, 0): '1101', (4, 0): '111010000', (-1, 0): '11101', (-2, 0): '11100',
             (-3, 0): '10001', (-1, -1): '110', (1, 1): '1110', (1, -1): '111010', (2, 3): '1011', (0, 2): '1110100', (10, 0): '111001100'}
    ok = all(numeral(to_digits(z)) == s and val([int(c) for c in reversed(s)]) == z and f"`{s}`" in p4 for z, s in table.items())
    report(f"§6.1: the {len(table)} numerals of the table are the unique base-(i−1) expansions, and appear in the README", ok)

    # ---- §6.3: the carry table  t -> t + 110
    m = re.search(r'\n t:\s+(.*)\n t\+110:\s+(.*)\n', p4)
    ts, us = m.group(1).split(), m.group(2).split()
    def add_num(a, b): return numeral(to_digits(gadd(val([int(c) for c in reversed(a)]), val([int(c) for c in reversed(b)]))))
    ok = len(ts) == 10 and all(add_num(t, '110') == u for t, u in zip(ts, us))
    report("§6.3: the ten-entry table t ↦ t + 110 is arithmetically right", ok)
    carries = re.search(r'The reachable carries are 15 numerals \((.*?)\);', p4).group(1).replace('`', '').split(', ')
    report("§6.3: the 15 listed carry numerals are distinct", len(carries) == 15 == len(set(carries)))

    # ---- the numbers quoted by hand: quick start (§2) and the convergence table (§10.2)
    z14 = f"{pi_N(14).numerator}/{pi_N(14).denominator} + {e_N(14).numerator}/{e_N(14).denominator} i"
    report("§2: the quoted value of z at N = 14 is the exact Euler partial sum π₁₄ + e₁₄·i", z14 in p1)
    ok = True
    for ln in p6.split('\n'):
        mm = re.match(r'\| (\d+) \| ([\d.]+) \| ([\d.]+) \|$', ln)
        if mm:
            N = int(mm.group(1))
            for txt, v in ((mm.group(2), pi_N(N)), (mm.group(3), e_N(N))):
                k = len(txt.split('.')[1]); ok &= (f"{float(v):.{k}f}" == txt)
                if f"{float(v):.{k}f}" != txt: print("   ?", N, txt, f"{float(v):.{k}f}")
    report("§10.2: the convergence table (N = 4, 8, 12, 16, 30) is right", ok)
    import math
    ok = abs(math.cos(0.5) - 0.8775825619) < 1e-10 and abs(math.sin(0.5) - 0.4794255386) < 1e-10
    report("§15.2: cos ½ = 0.8775825619, sin ½ = 0.4794255386", ok and '0.8775825619' in part(7) and '0.4794255386' in part(7))

    # ---- §6.3: the subtractor's carry count; §12.3: the binary spelling of the truth values; §1: doc 1 holds main
    n_sub = len(mkcarry.closure((-1, 0, 1)))
    report(f"§6.3: the subtractor has {n_sub} carry numerals, as written", f"with {n_sub} carry numerals" in p4 and n_sub == 47)
    pre = Program()
    t_code, f_code = pre.doc1.s2b['⊤'], pre.doc1.s2b['⊥']
    report(f"§12.3: true and false are spelled {t_code} and {f_code} in bin", f"`{t_code}` / `{f_code}` (bin)" in p6)
    report("§12.1: main has a doc 1 code, so a binary program has an entry point", 'main' in pre.doc1.s2b)

    print(f"\n{sum(RESULTS)}/{len(RESULTS)} passed  ({time.time()-t0:.1f}s)")
    return all(RESULTS)

_pre = None
def prelude_statements():
    global _pre
    if _pre is None:
        _pre = Program()
        for f in imo.PRELUDE: _pre.add_file(f, trusted=True)
    return _pre.statements

if __name__ == '__main__':
    sys.exit(0 if main() else 1)
