#!/bin/sh
# gen_data.sh -- the system files of the language as Racket source (schimo/src/data-gen.rkt): docs/doc1.sbl, docs/doc2.sbl and the files of
# lib/MANIFEST in loading order, as here strings, so that schimo carries the same prelude as the other cores.
cd "$(dirname "$0")/.." || exit 1
out=schimo/src/data-gen.rkt
for f in docs/doc1.sbl docs/doc2.sbl lib/*.imo; do
  if grep -q '^IMOEOF$' "$f"; then echo "gen_data.sh: $f contains the terminator line IMOEOF" >&2; exit 1; fi
done
{
  echo '#lang racket/base'
  echo ';; generated by schimo/gen_data.sh: do not edit'
  echo '(provide data-doc1 data-doc2 lib-files)'
  echo '(define data-doc1 #<<IMOEOF'; cat docs/doc1.sbl; echo; echo 'IMOEOF'; echo ')'
  echo '(define data-doc2 #<<IMOEOF'; cat docs/doc2.sbl; echo; echo 'IMOEOF'; echo ')'
  echo '(define lib-files (list'
  while IFS= read -r name; do
    name=$(printf '%s' "$name" | tr -d '\r')
    case "$name" in ''|'⍝'*) continue ;; esac
    echo "(cons \"lib/$name\" #<<IMOEOF"; cat "lib/$name"; echo; echo 'IMOEOF'; echo ')'
  done < lib/MANIFEST
  echo '))'
} > "$out.tmp" && mv "$out.tmp" "$out"
