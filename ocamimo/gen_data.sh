#!/bin/sh
# gen_data.sh -- the system files of the language as OCaml source (ocamimo/src/data_gen.ml): docs/doc1.sbl, docs/doc2.sbl and the files
# of lib/MANIFEST in loading order, as quoted string literals, so that ocamimo is one relocatable file with the same prelude as the other cores.
cd "$(dirname "$0")/.." || exit 1
out=ocamimo/src/data_gen.ml
for f in docs/doc1.sbl docs/doc2.sbl lib/*.imo; do
  if grep -q '|imo}' "$f"; then echo "gen_data.sh: $f contains the closing quote |imo}" >&2; exit 1; fi
done
{
  echo "(* generated by ocamimo/gen_data.sh: do not edit *)"
  printf 'let doc1 = {imo|'; cat docs/doc1.sbl; echo '|imo}'
  printf 'let doc2 = {imo|'; cat docs/doc2.sbl; echo '|imo}'
  echo 'let lib_files = ['
  while IFS= read -r name; do
    name=$(printf '%s' "$name" | tr -d '\r')
    case "$name" in ''|'⍝'*) continue ;; esac
    printf '  ("lib/%s", {imo|' "$name"; cat "lib/$name"; echo '|imo});'
  done < lib/MANIFEST
  echo ']'
} > "$out.tmp" && mv "$out.tmp" "$out"
