"""mkprove.py -- write the codes of the symbols that the prover of lib/prove.imo reasons about into that file (block  ⍝ <mkprove> … ⍝ </mkprove>).
The prover receives terms as codes, a symbol as its doc 1 code (a numeral); this block names those numerals, so the prover and doc 1
cannot disagree (the test-suite runs  --check).        python3 pymo/mkprove.py [--check]"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from layers import Doc1
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SYMS = ['⊞', '⊟', '⊠', '⊖', '∗', '÷', '⊕', '⊛', '⊖ᴿ', '⊟ᴿ', '∗ᴿ', '⇡', 'Σ', '∧', '∨', '¬', '⇒', '⇔',
        '≐ᴿ', '≠ᴿ', '≺ᴿ', '⩽ᴿ', '≻ᴿ', '⩾ᴿ', '√',
        '≐', '≠', '≺', '⩽', '≻', '⩾', '^', '^ᴿ', 'ℜ', 'ℑ', 'ℜᴿ', 'ℑᴿ', '⊤', '⊥', '𝔲',
        '÷ᴿ', 'root', '∷', '⊘', 'exp', 'sin', 'cos', 'sinh', 'cosh', 'log', 'atan']

def block(d1):
    L = ["⍝ <mkprove>  generated by pymo/mkprove.py from doc 1 — do not edit by hand"]
    for s in SYMS:
        code = d1.s2b[s][1:-1]
        L.append(f"ᶜ{s} ∶ 𝔇")
        L.append(f"ᶜ{s} ≔ (◀ {code})")
    L.append("⍝ </mkprove>")
    return '\n'.join(L) + '\n'

def main():
    d1 = Doc1.parse(open(os.path.join(ROOT, 'docs', 'doc1.sbl'), encoding='utf-8').read())
    p = os.path.join(ROOT, 'lib', 'prove.imo')
    s = open(p, encoding='utf-8').read()
    a, b = s.index('⍝ <mkprove>'), s.index('⍝ </mkprove>'); b = s.index('\n', b) + 1
    new = block(d1)
    if '--check' in sys.argv:
        ok = s[a:b] == new
        print("up to date" if ok else "lib/prove.imo: the symbol codes are out of date (run pymo/mkprove.py)"); return 0 if ok else 1
    open(p, 'w', encoding='utf-8').write(s[:a] + new + s[b:]); print("symbol codes written to lib/prove.imo"); return 0

if __name__ == '__main__':
    sys.exit(main())
