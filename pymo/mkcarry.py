"""mkcarry.py -- derive the carry tables of the serial adder and subtractor of base i-1 and write them into lib/number.imo
as decision trees on the low digits (the block between the markers  ⍝ <mkcarry>  and  ⍝ </mkcarry>).

  adder       x + y + c,  c = d + b·t:   o = x⊕y⊕d,  m = majority(x, y, d),          c' = t + m·110
  subtractor  x − y + c,  c = d + b·t:   o = x⊕y⊕d,  s = (x − y + d − o)/2 ∈ {−1,0,1},  c' = t + s·110
                                          (110 = b + b² = −1 − i,  and  2 = b² + b³)
The carries that can occur are closed under  c ↦ tail(c) + {0, ±110}; they are computed here, from the start carry 0, so the tables
are exactly the transitions that can happen.  A table is compiled into a binary decision tree that reads the low digits of the tail
(a missing digit is 0), so a lookup is a few digit tests, never a search.

  python3 pymo/mkcarry.py           rewrite the generated block of lib/number.imo
  python3 pymo/mkcarry.py --check   only check that the block is up to date"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from base_b import val, to_digits, numeral, gadd
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K = (-1, -1)                                       # 110

def closure(steps):
    seen, fr = {(0, 0)}, [(0, 0)]
    while fr:
        c = fr.pop(); t = val(to_digits(c)[1:])
        for s in steps:
            n = gadd(t, (s * K[0], s * K[1]))
            if n not in seen: seen.add(n); fr.append(n)
    return seen

def tails(carries):
    return sorted({tuple(to_digits(c)[1:]) for c in carries}, key=lambda t: (len(t), t))

def digit(t, k): return t[k] if k < len(t) else 0

def tree(entries, k, var='ξ'):
    """entries: [(tail digits, output digits)] -> spec expression choosing the output by the digits of the tail"""
    outs = {tuple(o) for _, o in entries}
    if len(outs) == 1:
        o = list(entries[0][1])
        return f"(◀ {numeral(o)})"
    one = [e for e in entries if digit(e[0], k) == 1]
    zero = [e for e in entries if digit(e[0], k) == 0]
    if not one: return tree(zero, k + 1, var)
    if not zero: return tree(one, k + 1, var)
    d = var
    for _ in range(k): d = f"(⌄ {d})"
    return f"((⌃ {d}) {tree(one, k + 1, var)} {tree(zero, k + 1, var)})"

def table(ts, shift):
    return [(t, to_digits(gadd(val(list(t)), (shift * K[0], shift * K[1])))) for t in ts]

def block():
    add_c = closure((0, 1)); sub_c = closure((-1, 0, 1))
    at, st = tails(add_c), tails(sub_c)
    lines = [
        "⍝ <mkcarry>  generated by pymo/mkcarry.py — do not edit by hand",
        f"⍝ adder: {len(add_c)} carry numerals, {len(at)} tails.   ⌕′ t = t + 110, the table κ compiled into a decision tree on the low digits of the tail",
        "⌕′ ∶ 𝔇 → 𝔇",
        f"⌕′ ξ ≔ {tree(table(at, 1), 0)}",
        f"⍝ subtractor: {len(sub_c)} carry numerals, {len(st)} tails.   ⌕⁺ t = t + 110,  ⌕⁻ t = t − 110 = t + 1110",
        "⌕⁺ ∶ 𝔇 → 𝔇",
        f"⌕⁺ ξ ≔ {tree(table(st, 1), 0)}",
        "⌕⁻ ∶ 𝔇 → 𝔇",
        f"⌕⁻ ξ ≔ {tree(table(st, -1), 0)}",
        "⍝ </mkcarry>",
    ]
    return '\n'.join(lines) + '\n', len(add_c), len(sub_c)

def main():
    p = os.path.join(ROOT, 'lib', 'number.imo')
    s = open(p, encoding='utf-8').read()
    a, b = s.index('⍝ <mkcarry>'), s.index('⍝ </mkcarry>')
    b = s.index('\n', b) + 1
    new, na, ns = block()
    if '--check' in sys.argv:
        ok = s[a:b] == new
        print("up to date" if ok else "lib/number.imo: the generated carry tables are out of date"); return 0 if ok else 1
    open(p, 'w', encoding='utf-8').write(s[:a] + new + s[b:])
    print(f"carry tables written: adder {na} carries, subtractor {ns} carries")
    return 0

if __name__ == '__main__':
    sys.exit(main())
