def measure(argv):
    """(seconds, peak resident memory in MB) of a command.  The peak is read from /proc while the command runs: getrusage would
    include the memory of this (large) process at the moment of the fork."""
    t = time.time()
    p = subprocess.Popen(argv, cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    peak = 0
    while p.poll() is None:
        try:
            for ln in open(f'/proc/{p.pid}/status'):
                if ln.startswith('VmHWM:'): peak = max(peak, int(ln.split()[1])); break
        except OSError: pass
        time.sleep(0.001)
    return time.time() - t, peak / 1024

