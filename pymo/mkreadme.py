def p_tree():
    rows = []
    def walk(d, prefix):
        items = {n for n in os.listdir(d) if n not in ('__pycache__', '.git', 'build', 'dist-newstyle', 'target') and not n.endswith('.pyc')}
        if d == ROOT: items.add('README.md')
        items = [n for n in items if not re.fullmatch(r'part[2-9]\.md', n)]
        items.sort(key=lambda n: (not os.path.isdir(os.path.join(d, n)), n.lower()))
        for i, n in enumerate(items):
            last = i == len(items) - 1
            full = os.path.join(d, n); isdir = os.path.isdir(full); rel = os.path.relpath(full, ROOT)
            note = TREE_NOTES.get(rel) or TREE_NOTES.get(n) or ROLE.get(rel, '')
            if n == 'part1.md': n, note = 'part1.md … part8.md', 'hand-written sections, with {{placeholders}}'
            big = isdir and sum(len(fs) for _, _, fs in os.walk(full)) > 40            # a directory of generated programs: one line, not a listing
            if big: note = (note + ' ' if note else '') + f"({sum(len(fs) for _, _, fs in os.walk(full))} files)"
            rows.append((prefix + ('└── ' if last else '├── ') + n + ('/' if isdir else ''), note))
            if isdir and not big: walk(full, prefix + ('    ' if last else '│   '))
    walk(ROOT, '')
    w = max(len(l) for l, _ in rows) + 2
    return '\n'.join(['i-1/'] + [(l.ljust(w) + ('# ' + n if n else '')).rstrip() for l, n in rows])

