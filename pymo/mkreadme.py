def p_file(p): t = read(p); return t if t.endswith('\n') else t + '\n'
def p_head(arg):
    p, n = arg.rsplit(':', 1)
    return '\n'.join(read(p).split('\n')[:int(n)])

_prelude = None
def prelude_program():
    global _prelude
    if _prelude is None:
        _prelude = Program()
        for f in imo.PRELUDE: _prelude.add_file(f, trusted=True)
        _prelude.check()
    return _prelude

def p_show(arg):
    names = arg.split()
    P = prelude_program()
    sts = [st for (f, st, t) in P.statements if st[0] in ('decl', 'def') and st[1] in names]
    # keep the order given in the placeholder, declaration before definition
    sts.sort(key=lambda s: (names.index(s[1]), 0 if s[0] == 'decl' else 1))
    spec = '\n'.join(syntax.pp_statement(s) for s in sts)
    bin_ = layers.spec_statements_to_bin_text(sts, P.doc1, allow_new=False).rstrip('\n')
    real = set(read('lib/prelude.bin.imo').split('\n'))
    for ln in bin_.split('\n'): assert ln in real, f"bin line is not in lib/prelude.bin.imo: {ln}"
    return "**spec**\n\n" + fence(spec) + "\n\n**bin** (the same statements, as they stand in `lib/prelude.bin.imo`)\n\n" + fence(bin_)

def p_triple(hum_text):
    P = Program()
    for f in imo.PRELUDE: P.add_file(f, trusted=True)
    P.add_text(hum_text, '<readme>', notation='hum'); P.check()
    assert not P.errors
    spec = P.spec_text(); bin_ = P.bin_text(); local = P.local_table() if P.doc1.local else ''
    out = ["**hum**\n\n" + fence(hum_text), "**spec**\n\n" + fence(spec), "**bin**\n\n" + fence(bin_)]
    if local:
        rows = [ln for ln in local.split('\n') if ' := ' in ln]
        out.append("program-local symbols the bin text introduced (same line format as doc 1; this is the `.sbl` file that goes with it):\n\n" + fence('\n'.join(rows)))
    return '\n\n'.join(out) + '\n'

