def p_humtable():
    P = Program()
    for f in imo.PRELUDE: P.add_file(f, trusted=True)
    P.add_file(path('examples/target.spec.imo'))         # declares π, 𝕖, 𝕫 so that the human names pi, e resolve
    base = len(P.statements)
    spans = []
    for row in HUM_ROWS:
        a = len(P.statements); P.add_text(row, '<readme>', notation='hum'); spans.append((a, len(P.statements)))
    P.check()
    assert not P.errors, P.errors
    resolved = [r for (f, s, t), r in zip(P.statements, P.resolved)]
    rows = ['| human | spec (after overload resolution and coercions) |', '|:--|:--|']
    for row, (a, b) in zip(HUM_ROWS, spans):
        spec = '<br>'.join('`' + syntax.pp_statement(resolved[k]).replace('|', '\\|') + '`' for k in range(a, b))
        rows.append(f"| `{row.replace('|', chr(92) + '|')}` | {spec} |")
    return '\n'.join(rows) + '\n'

def cfmt(re, im):
    """a + b i, with Unicode minus"""
    def f(x): return str(x).replace('-', '−')
    if im == 0: return f(re)
    ib = 'i' if abs(im) == 1 else f(abs(im)) + ' i'
    if re == 0: return ('−' if im < 0 else '') + ib
    return f"{f(re)} {'−' if im < 0 else '+'} {ib}"

NUMS = ['0', '1', '10', '11', '110', '1100', '1101', '11101', '10001', '111010000', '.1', '0.1', '1.1', '11.1', '1100.1']
def p_numtable():
    rows = ['| numeral | value in ℚ[i] | class the checker gives it |', '|:--|:--|:--|']
    for t in NUMS:
        if '.' in t:
            a, b = t.split('.'); bits, k = a + b, len(b)
        else:
            bits, k = t, 0
        z = val([int(c) for c in reversed(bits)])
        den = (1, 0)
        for _ in range(k): den = gmul(den, (-1, 1))
        n = den[0] ** 2 + den[1] ** 2
        re = Fraction(z[0] * den[0] + z[1] * den[1], n); im = Fraction(z[1] * den[0] - z[0] * den[1], n)
        v = cfmt(re, im)
        rows.append(f"| `{t}` | {v} | `{show_type(num_class(t))}` |")
    return '\n'.join(rows) + '\n'

