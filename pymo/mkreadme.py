def run(args, timeout=900):
    t = time.time()
    r = subprocess.run([PY, path('pymo/i1.py')] + shlex.split(args), cwd=ROOT, capture_output=True, text=True, timeout=timeout)
    return r.stdout.rstrip('\n'), time.time() - t

def fence(text, lang='text'): return f"```{lang}\n{text.rstrip(chr(10))}\n```"

