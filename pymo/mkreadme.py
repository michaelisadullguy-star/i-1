def expand(text):
    def sub(m):
        kind, _, arg = m.group(1).partition(':')
        if kind == 'FILE': return p_file(arg)
        if kind == 'HEAD': return p_head(arg)
        if kind == 'SHOW': return p_show(arg)
        if kind == 'TRIPLE': return p_triple(arg)
        if kind == 'HUMTABLE': return p_humtable()
        if kind == 'NUMTABLE': return p_numtable()
        if kind == 'REF': return read('docs/reference.generated.md')
        if kind == 'DOC2TABLE': return read('docs/doc2.generated.md')
        if kind == 'DOC1_COUNT': return str(len(Program().doc1.s2b))
        if kind == 'PRELUDE_BIN_CHARS': return f"{len(read('lib/prelude.bin.imo')):,}"
        if kind == 'RUNOUT':
            if arg not in CACHE: CACHE[arg] = run(arg)[0]
            return CACHE[arg]
        if kind == 'TESTLOG': return p_testlog()
        if kind == 'LOC': return p_loc()
        if kind == 'TIMES': return p_times()
        if kind == 'CONFORMANCE': return p_conformance()
        if kind == 'HSTIMES': return p_hstimes()
        if kind == 'TREE': return p_tree()
        raise SystemExit(f"unknown placeholder {{{{{m.group(1)}}}}}")
    def sub2(m):
        r = sub(m)
        return r if m.group(1).startswith('FILE:') else r.rstrip('\n')
    return re.sub(r'\{\{([A-Z0-9_]+(?::[^{}]*)?)\}\}', sub2, text)
CACHE = {}

def slug(h):
    h = re.sub(r'`', '', h.strip()).lower()
    h = re.sub(r'[^\w\- ]', '', h)
    return h.replace(' ', '-')

def check_links(md):
    heads, inside = set(), False
    for ln in md.split('\n'):
        if ln.strip().startswith('```') or ln.rstrip().endswith('```'): inside = not inside
        if not inside and re.match(r'#{1,6} ', ln): heads.add(slug(ln.lstrip('#')))
    links = set(re.findall(r'\]\(#([^)]+)\)', md))
    bad = sorted(a for a in links if a not in heads)
    bad += sorted(a for a in links if not a.isascii())       # anchors with non-ASCII characters are not portable
    return bad

def main():
    if '--tests' in sys.argv:                                  # every suite on every core it supports, four at a time, the output kept in tests/logs/
        r = subprocess.run([PY, path('tests/run_suites.py'), '--logs'], cwd=ROOT)
        if r.returncode: sys.exit("a test-suite failed")
    subprocess.run([PY, path('pymo/mkref.py')], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    parts = sorted(f for f in os.listdir(path('readme')) if re.fullmatch(r'part\d+\.md', f))
    md = ''.join(open(path('readme/' + f), encoding='utf-8').read() for f in parts)
    bad = check_links(md)                                  # fail fast: the headings and links are static text
    if bad: sys.exit(f"broken in-page links: {bad}")
    md = expand(md)
    left = re.findall(r'\{\{[A-Z0-9_]+[^}]*\}\}', md)
    # `{{placeholders}}` mentioned in the tree/FAQ as literal text are fine only inside the generated tree line
    left = [x for x in left if x != '{{placeholders}}']
    if left: sys.exit(f"unresolved placeholders: {left}")
    bad = check_links(md)
    if bad: sys.exit(f"broken in-page links: {bad}")
    open(path('README.md'), 'w', encoding='utf-8').write(md.rstrip('\n') + '\n')
    print(f"README.md: {len(md.split(chr(10)))} lines, {len(md):,} characters from {len(parts)} parts")

if __name__ == '__main__':
    main()
