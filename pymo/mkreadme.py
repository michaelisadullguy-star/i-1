def test_times():
    """suite -> (checks, seconds on Pymo, seconds on Haskimo or None, seconds on Rustimo or None); None for a suite that runs on Pymo only"""
    res = {}
    for f in ALL:
        m = re.search(r'(\d+)/(\d+) passed\s+\(([\d.]+)s\)', read(f'tests/logs/{f}.txt'))
        assert m and m.group(1) == m.group(2), f"{f}: not all tests passed"
        other = {}
        for core, label in (('haskimo', 'Haskimo'), ('rustimo', 'Rustimo')):
            other[core] = None
            if os.path.exists(path(f'tests/logs/{f}.{core}.txt')):
                mh = re.search(r'(\d+)/(\d+) passed\s+\(([\d.]+)s\)', read(f'tests/logs/{f}.{core}.txt'))
                assert mh and mh.group(1) == mh.group(2) == m.group(2), f"{f}: not all tests passed on {label} (or a different number of checks)"
                other[core] = float(mh.group(3))
        res[f] = (int(m.group(2)), float(m.group(3)), other['haskimo'], other['rustimo'])
    return res

