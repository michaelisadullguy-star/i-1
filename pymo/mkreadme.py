"""
mkreadme.py -- assemble README.md from readme/part*.md.

The parts are hand-written markdown with {{PLACEHOLDERS}}; everything a placeholder stands for is *generated by running the
implementation*, so the README cannot drift from the code.

  python3 pymo/mkreadme.py            build README.md (uses the saved test logs in tests/logs/)
  python3 pymo/mkreadme.py --tests    first re-run all test-suites on every core they support (tests/run_suites.py) and save their output to tests/logs/

Placeholders
  {{FILE:path}}            the file's text (ends with a newline, so the closing fence can follow directly)
  {{HEAD:path:n}}          the first n lines of a file (no trailing newline)
  {{SHOW:sym sym ...}}     declaration + definition of the prelude symbols, in spec and in bin (bin lines are checked to occur in prelude.bin.imo)
  {{TRIPLE:human text}}    the same statement(s) in hum, spec and bin notation, produced by the translators
  {{HUMTABLE}}             curated human statements and the spec they compile to
  {{NUMTABLE}}             numerals, their values and classes
  {{REF}}  {{DOC2TABLE}}   the generated reference tables (pymo/mkref.py is run first)
  {{DOC1_COUNT}}  {{PRELUDE_BIN_CHARS}}
  {{RUNOUT:args}}          stdout of  python3 pymo/i1.py args
  {{TESTLOG}}  {{LOC}}  {{TIMES}}  {{TREE}}
"""
