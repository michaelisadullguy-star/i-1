#!/bin/sh
# gen_data.sh -- the system files of the language as C source (cimo/src/data_gen.c): docs/doc1.sbl, docs/doc2.sbl and the files of lib/MANIFEST in
# loading order, as byte arrays, so that cimo is one relocatable file with the same prelude as the other cores.
cd "$(dirname "$0")/.." || exit 1
out=cimo/src/data_gen.c
emit() {
  printf 'static const unsigned char %s[] = {\n' "$1"
  od -An -v -tx1 "$2" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1,/g'
  printf '0};\n'
}
{
  echo '/* generated by cimo/gen_data.sh: do not edit */'
  emit doc1_bytes docs/doc1.sbl
  emit doc2_bytes docs/doc2.sbl
  names=""
  k=0
  while IFS= read -r name; do
    name=$(printf '%s' "$name" | tr -d '\r')
    case "$name" in ''|'⍝'*) continue ;; esac
    emit "lib_$k" "lib/$name"
    k=$((k + 1))
  done < lib/MANIFEST
  echo 'const char *DOC1 = (const char *)doc1_bytes;'
  echo 'const char *DOC2 = (const char *)doc2_bytes;'
  printf 'const char *LIB_NAMES[] = {\n'
  grep -v '^⍝' lib/MANIFEST | tr -d '\r' | grep -v '^$' | while IFS= read -r name; do printf '  "lib/%s",\n' "$name"; done
  printf '  0 };\n'
  printf 'const char *LIB_TEXTS[] = {\n'
  i=0
  while [ $i -lt $k ]; do printf '  (const char *)lib_%s,\n' "$i"; i=$((i + 1)); done
  printf '  0 };\n'
} > "$out.tmp" && mv "$out.tmp" "$out"
